/**
 * Imports Anthropic prices from the community dataset at a pinned commit (ADR-0006).
 *
 *   pnpm --filter @ai-unit-economics/pricing-data import:litellm <commit-sha>
 *
 * Writes the vendored Anthropic slice to snapshot/ and appends a row to the rate table for
 * every model whose rates are new or changed. Existing rows are never modified.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { ANTHROPIC_RATES } from '../anthropic/anthropic.rates.js';
import { toPerMillionTokens } from '../decimal.util.js';
import type { LongContextRates, PricingRate, TokenRates } from '../pricing-rate.type.js';
import { computePricingVersion } from '../pricing-version.util.js';

const REPOSITORY = 'BerriAI/litellm';
const PATH = 'model_prices_and_context_window.json';
const LONG_CONTEXT_THRESHOLD = 200_000;

type UpstreamEntry = Record<string, unknown>;

const sha = parseSha(process.argv[2]);

const committedAt = await fetchCommitDate(sha);
const upstream = (await fetchJson(
  `https://raw.githubusercontent.com/${REPOSITORY}/${sha}/${PATH}`,
)) as Record<string, UpstreamEntry>;

const entries = Object.fromEntries(
  Object.entries(upstream)
    .filter(([, entry]) => entry.litellm_provider === 'anthropic')
    .sort(([a], [b]) => (a < b ? -1 : 1)),
);

await writeFile(
  packagePath('snapshot/litellm-anthropic.json'),
  `${JSON.stringify({ upstream: { repository: REPOSITORY, path: PATH, sha, committedAt }, entries }, null, 2)}\n`,
);

const rows = [...ANTHROPIC_RATES];
const appended: string[] = [];
for (const [model, entry] of Object.entries(entries)) {
  const candidate = toRow(model, entry);
  if (!candidate) continue;
  const current = rows.filter((r) => r.model === model).at(-1);
  if (current && sameRates(current, candidate)) continue;
  if (current && current.validFrom >= candidate.validFrom) {
    throw new Error(`${model}: snapshot ${committedAt} is not newer than ${current.validFrom}`);
  }
  rows.push(candidate);
  appended.push(model);
}

rows.sort((a, b) =>
  a.model < b.model ? -1 : a.model > b.model ? 1 : a.validFrom < b.validFrom ? -1 : 1,
);
const version = computePricingVersion('anthropic', rows);
await writeFile(packagePath('src/anthropic/anthropic.rates.ts'), renderTable(version, rows));

console.log(`snapshot ${sha} (${committedAt}): ${Object.keys(entries).length} Anthropic entries`);
console.log(appended.length ? `appended: ${appended.join(', ')}` : 'no rate changes');
console.log(`pricing version: ${version}`);

function toRow(model: string, entry: UpstreamEntry): PricingRate | null {
  const standard = tokenRates(entry, '');
  if (!standard) {
    console.warn(`skipped ${model}: no input/output price`);
    return null;
  }
  return {
    provider: 'anthropic',
    model,
    validFrom: committedAt,
    currency: 'USD',
    standard,
    batch: tokenRates(entry, '_batches'),
    longContext: longContextRates(entry),
    provenance: {
      source: `https://github.com/${REPOSITORY}/blob/${sha}/${PATH}`,
      snapshotSha: sha,
      observedAt: committedAt,
      // Upstream carries no effective dates; we only know when the price was observable.
      effectiveAt: null,
      confidence: 'OBSERVED',
    },
  };
}

function tokenRates(entry: UpstreamEntry, suffix: string, tier = ''): TokenRates | null {
  const input = price(entry, `input_cost_per_token${tier}${suffix}`);
  const output = price(entry, `output_cost_per_token${tier}${suffix}`);
  if (input === null || output === null) return null;
  return {
    input,
    output,
    cacheRead: price(entry, `cache_read_input_token_cost${tier}${suffix}`),
    cacheWrite5m: price(entry, `cache_creation_input_token_cost${tier}${suffix}`),
    cacheWrite1h: price(
      entry,
      tier
        ? `cache_creation_input_token_cost_above_1hr${tier}${suffix}`
        : `cache_creation_input_token_cost_above_1hr${suffix}`,
    ),
  };
}

function longContextRates(entry: UpstreamEntry): LongContextRates | null {
  const tier = `_above_${LONG_CONTEXT_THRESHOLD / 1000}k_tokens`;
  const standard = tokenRates(entry, '', tier);
  if (!standard) return null;
  return {
    aboveInputTokens: LONG_CONTEXT_THRESHOLD,
    standard,
    batch: tokenRates(entry, '_batches', tier),
  };
}

function price(entry: UpstreamEntry, key: string): string | null {
  const value = entry[key];
  return typeof value === 'number' ? toPerMillionTokens(value) : null;
}

function sameRates(a: PricingRate, b: PricingRate): boolean {
  const pick = (r: PricingRate) => JSON.stringify([r.standard, r.batch, r.longContext]);
  return pick(a) === pick(b);
}

function renderTable(version: string, table: PricingRate[]): string {
  return `// Generated by src/cli/import-litellm.ts. Do not edit by hand except to upgrade a row's
// provenance to EXACT with a cited source; never change a rate in place — append a row.
import type { PricingRate } from '../pricing-rate.type.js';

export const ANTHROPIC_PRICING_VERSION = '${version}';

export const ANTHROPIC_RATES: readonly PricingRate[] = ${JSON.stringify(table, null, 2)};
`;
}

async function fetchCommitDate(commit: string): Promise<string> {
  const body = (await fetchJson(
    `https://api.github.com/repos/${REPOSITORY}/commits/${commit}`,
  )) as {
    commit: { committer: { date: string } };
  };
  return new Date(body.commit.committer.date).toISOString();
}

async function fetchJson(url: string): Promise<unknown> {
  const response = await fetch(url, {
    headers: { 'user-agent': 'ai-unit-economics-pricing-import' },
  });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return response.json();
}

function parseSha(arg: string | undefined): string {
  if (!arg || !/^[0-9a-f]{40}$/.test(arg)) {
    console.error('usage: import:litellm <40-char commit sha>');
    process.exit(1);
  }
  return arg;
}

function packagePath(relative: string): string {
  return fileURLToPath(new URL(`../../${relative}`, import.meta.url));
}
